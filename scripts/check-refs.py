#!/usr/bin/env python3
"""Check cross-references without rendering.

The site is made of *documents*: the combined architecture document
(everything in architecture/ except index.qmd) and each analysis folder.
Within each document this reports:

- @sec-/@fig-/@tbl- references that do not resolve to an ID defined in that
  document (generated IDs from Python cells are not visible here, so a
  reference to one is reported as "possibly generated" rather than failed);
- hand-typed "chapter 7", "section 3.1", "appendix A" — use a
  cross-reference instead, so the number cannot drift;
- a line that starts with "@ref)", "@ref." or "(@ref)": Pandoc reads that as
  an example-list marker and every @ref to that ID then renders as a bare
  number. Rewrap so the line starts with other text.

Run from the repository root:  python3 scripts/check-refs.py
Exits non-zero if anything failed.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

documents = {}
arch = [p for p in sorted(ROOT.glob("architecture/*"))
        if p.suffix in (".md", ".qmd") and p.name not in ("index.qmd", "complete.qmd")]
if arch:
    documents["architecture"] = arch
for folder in sorted(ROOT.glob("analysis/*/")):
    if folder.name.startswith("_"):
        continue
    files = [p for p in sorted(folder.rglob("*")) if p.suffix in (".md", ".qmd")]
    if files:
        documents[str(folder.relative_to(ROOT))] = files

REF = re.compile(r"@((?:sec|fig|tbl)-[\w-]*\w)")
HAND = re.compile(
    r"\b(?:chapters?|sections?|appendix|appendices|ch\.)\s+"
    r"(?:\d+(?:\.\d+)*|[A-H]\b)|§\s*\d",
    re.I,
)
EXAMPLE = re.compile(r"^[ \t]*\(?@[\w-]*\w[.)](?=\s|$)", re.M)
ID = re.compile(r"\{#((?:sec|fig|tbl)-[\w-]+)[\s}]")
# Anything in a code cell that looks like it will become an ID: a cell label,
# or an ID fragment inside a printed string (an f-string gives a prefix only).
IN_CODE = re.compile(r"(?:label:\s*|#)((?:sec|fig|tbl)-[\w-]+)")

failed = warned = 0


def strip_code(path):
    """Blank fenced code (keeping line breaks) and collect the ID fragments a
    code cell might generate."""
    lines, fence, generated = [], False, set()
    for line in path.read_text().splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            fence = not fence
            lines.append("")
        elif fence:
            generated.update(IN_CODE.findall(line))
            lines.append("")
        else:
            lines.append(line)
    return "\n".join(lines), generated


def report(path, text, pos, message, warning=False):
    global failed, warned
    line = text.count("\n", 0, pos) + 1
    print(f"{'warning' if warning else 'error'}: {path.relative_to(ROOT)}:{line}: {message}")
    if warning:
        warned += 1
    else:
        failed += 1


for name, files in documents.items():
    texts, ids, generated = {}, {}, set()
    for f in files:
        text, gen = strip_code(f)
        texts[f] = text
        generated |= gen
        for n, line in enumerate(text.splitlines(), 1):
            for i in ID.findall(line):
                if i in ids:
                    print(f"error: {f.relative_to(ROOT)}:{n}: duplicate ID #{i} (also {ids[i]})")
                    failed += 1
                ids[i] = f"{f.relative_to(ROOT)}:{n}"
    for f, text in texts.items():
        for m in REF.finditer(text):
            ref = m.group(1)
            if ref in ids:
                continue
            if any(ref == g or ref.startswith(g.rstrip("-") + "-") for g in generated):
                report(f, text, m.start(), f"@{ref} is possibly generated by a code cell — check the render", warning=True)
            else:
                report(f, text, m.start(), f"unresolved @{ref} in document '{name}'")
        for m in HAND.finditer(text):
            report(f, text, m.start(), f"hand-typed reference '{' '.join(m.group(0).split())}'")
        for m in EXAMPLE.finditer(text):
            report(f, text, m.start(), "line starts with a reference Pandoc will read as a list marker")

summary = f"{failed} error(s), {warned} warning(s)" if (failed or warned) else "Cross-references OK"
print(summary)
sys.exit(1 if failed else 0)
